clear; clc; clf; hold on;

load results\isoisoex_MAP_results_081.mat

indx = [1:14,16:29,31:34];
H = schur_comp(hessian, indx);
mu = x(indx);

Nsamp = 300;

SIGMA = inv(H);
samples = mvnrnd(mu, 0.5*(SIGMA+SIGMA'), Nsamp);

T = (300:100:900)';
Ts = (300:900)';

consts = load("isoisoex_constants.mat");


for i = 1:Nsamp
    K = blkdiag( ...
        RBFKernel(T,T,log(consts.sigma_lnkf), log(consts.sigma_lnkf), samples(i, 29)), ...
        RBFKernel(T,T,log(consts.sigma_lnCf), log(consts.sigma_lnCf), samples(i, 30)), ...
        RBFKernel(T,T,log(consts.sigma_lnks), log(consts.sigma_lnks), samples(i, 31)), ...
        RBFKernel(T,T,log(consts.sigma_lnCs), log(consts.sigma_lnCs), samples(i, 32)) ...
    );
    Ks = blkdiag( ...
        RBFKernel(T,Ts,log(consts.sigma_lnkf), log(consts.sigma_lnkf), samples(i, 29)), ...
        RBFKernel(T,Ts,log(consts.sigma_lnCf), log(consts.sigma_lnCf), samples(i, 30)), ...
        RBFKernel(T,Ts,log(consts.sigma_lnks), log(consts.sigma_lnks), samples(i, 31)), ...
        RBFKernel(T,Ts,log(consts.sigma_lnCs), log(consts.sigma_lnCs), samples(i, 32)) ...
    );
    Kss = blkdiag( ...
        RBFKernel(Ts,Ts,log(consts.sigma_lnkf), log(consts.sigma_lnkf), samples(i, 29)), ...
        RBFKernel(Ts,Ts,log(consts.sigma_lnCf), log(consts.sigma_lnCf), samples(i, 30)), ...
        RBFKernel(Ts,Ts,log(consts.sigma_lnks), log(consts.sigma_lnks), samples(i, 31)), ...
        RBFKernel(Ts,Ts,log(consts.sigma_lnCs), log(consts.sigma_lnCs), samples(i, 32)) ...
    );
    Vs = K \ Ks;

    MU0 = [consts.mu_lnkf, consts.mu_lnCf, consts.mu_lnks, consts.mu_lnCs] .* ones(numel(T), 1);
    mu0v = MU0(:);
    MU0s = [consts.mu_lnkf, consts.mu_lnCf, consts.mu_lnks, consts.mu_lnCs] .* ones(numel(Ts), 1);
    mu0vs = MU0s(:);

    mus = mu0vs + Vs.' * (samples(i,1:28).' - mu0v);
    MUs = reshape(mus, length(Ts), []);

    figure(1);
    patch([Ts; NaN], [exp(MUs(:,1)-MUs(:,2)); NaN], 'k', ...
    'FaceColor', 'none', ...
    'EdgeColor', 'k', ...
    'EdgeAlpha', 0.1);

    figure(2)
    patch([Ts; NaN], [exp(MUs(:,3)-MUs(:,4)); NaN], 'k', ...
    'FaceColor', 'none', ...
    'EdgeColor', 'k', ...
    'EdgeAlpha', 0.1);
end